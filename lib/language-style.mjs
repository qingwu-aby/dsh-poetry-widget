// lib/language-style.mjs —— 她说话的“去 AI 味”约束（v1.61）。
//
// 参考 https://github.com/LifelongLazyLearner/qu-ai-wei 的编辑思路，但做两处批判性调整：
//   · 那个仓库是“改写已有文本、并保留事实与作者声口”的编辑 skill，不是生成模板；
//     直接把它当词表/黑名单会制造另一种机械感，所以这里只取结构线索，不列禁词。
//   · 它明确反对“为了人味硬加错字、口头语、emoji、第一人称”，这里同样不鼓励表演式口语。
// 目标：让她像在心里说话，而不是像在写文章/写报告/写总结。

/** 通用自然语言约束（短、可执行；不依赖具体词表）。 */
export const NATURAL_LANGUAGE_RULES = Object.freeze([
  '写具体的东西：动作、物件、时间、身体感受、当时的光线或声音；少写「某种意义上」「总的来说」「值得注意」「不得不说」这类没有新信息的话。',
  '别用「不是……而是……」「不仅……更……」「既是……也是……」「看似……其实……」这类对称骨架，也别凑三项排比；有一说一，句子长短错开。',
  '少用抽象名词和空动词（进行、实现、推动、构建、体现、赋能、闭环），直接写谁做了什么。',
  '连接词能省就省：因此、然而、此外、这说明、由此可见，只在关系真的存在时才用。',
  '不解释自己在说什么，不总结、不升华、不在结尾摆结论；说完一件小事就停，哪怕停在半截。',
  '不要为了「像人」故意加错字、口头禅、方言、网络热词，也别用 emoji 或堆感叹号。',
  '不确定就写不确定（说不好、没弄明白、可能吧），但别叠「或许／可能／某种程度上」。',
  '不要用破折号和分号装作停顿或层次；句子该断就断，该短就短。',
  '像在心里说话，不像在写文章：可以有忽然想起的细节或没说完的话，但不要漂亮的空话。',
])

/**
 * 追加到生成 prompt 末尾的自然语言约束。
 * @param {string[]} [extra] 该场景额外的风格要求（如“理由只写一两件具体的事”）
 * @returns {string[]}
 */
export function naturalStyleLines(extra = []) {
  const lines = [...NATURAL_LANGUAGE_RULES]
  if (Array.isArray(extra)) {
    for (const item of extra) {
      if (typeof item === 'string' && item.trim().length > 0) lines.push(item.trim())
    }
  }
  return lines
}
