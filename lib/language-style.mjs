// lib/language-style.mjs —— 她说话/写字的「说人话」约束（v2.41）。
//
// 参考两个来源，并做批判性调整：
//   · qu-ai-wei：去 AI 腔的结构线索（对称骨架、空动词、提示语、总结升华）；
//   · MrGeDiao/shuorenhua（说人话）：删招呼/预告/致谢、去名词化绕弯、同义重复，
//     保留事实、条件、承诺和作者口气；不为“像人”硬加错字、口头禅、emoji。
//
// 关键不是“加人味”，而是**允许普通、无聊、没写完**：人多数时候在想事、做事、
// 走神，不是在写微散文。禁止每句都写画面、金句和比喻。

/** 通用自然语言约束（短、可执行；不依赖具体词表）。 */
export const NATURAL_LANGUAGE_RULES = Object.freeze([
  '直接从事情本身说起；删掉招呼、预告、致谢，以及没有具体内容的开场和收尾。',
  '谁做了什么就写谁做了什么；不要写成「完成了对……的调整」「进行了……的思考」这种绕弯的说法。',
  '同一件事只说一遍；不要换个词再说一遍。',
  '不要每句都写画面、光线、风、杯子、纸角、掌心；人多数时候是在想事、做事、走神，不是在写散文。',
  '少用比喻、拟人、通感；一个段落最多一个具体意象，没有也行。不要写金句。',
  '允许平常、无聊、没劲、半截话、改口；不是每句都要漂亮或完整。',
  '心里的话可以有事务性内容：待会儿做什么、几点了、东西放哪、今天还没干嘛、要不要算了。',
  '口语就用口语词：算了、懒得、待会儿、忘了、还行、有点烦；但别为了像人硬塞口头禅、错字或网络热词。',
  '不总结、不升华、不解释自己的情绪；不要用「我意识到」「这说明」「像……一样」收尾。',
  '少用抽象名词和空动词（进行、实现、推动、构建、体现、赋能、闭环），直接写动作。',
  '连接词能省就省：因此、然而、此外、这说明、由此可见，只在关系真的存在时才用。',
  '不要用「不是……而是……」「不仅……更……」「既是……也是……」「看似……其实……」这类对称骨架，也别凑三项排比。',
  '不要用破折号和分号装作停顿或层次；句子该断就断，该短就短。',
  '不要 emoji、不要堆感叹号，也不要为了「像人」故意写错字或方言。',
  '不确定就写不确定（说不好、没弄明白、可能吧），但别叠「或许／可能／某种程度上」。',
])

/**
 * 追加到生成 prompt 末尾的自然语言约束。
 * @param {string[]} [extra] 该场景额外的风格要求
 * @returns {string[]}
 */
export function naturalStyleLines(extra = []) {
  const lines = [...NATURAL_LANGUAGE_RULES]
  if (Array.isArray(extra)) {
    for (const item of extra) {
      if (typeof item === 'string' && item.trim().length > 0) lines.push(item.trim())
    }
  }
  return lines
}
