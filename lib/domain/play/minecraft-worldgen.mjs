/** 按主题匹配材料知识；匹配不到返回 null。 */
export function lookupWorldgen(topic) {
  const text = String(topic ?? '').toLowerCase()
  if (text.length === 0) return null
  let best = null
  let bestScore = 0
  for (const entry of ENTRIES) {
    let score = 0
    for (const key of entry.keys) {
      const k = key.toLowerCase()
      if (text.includes(k)) score += k.length >= 2 ? k.length : 1
    }
    if (score > bestScore) { best = entry; bestScore = score }
  }
  if (best === null) return null
  return { method: best.method, steps: best.steps.slice(), caveat: '材料知识（不联网）', source: 'worldgen', title: best.keys[0] }
}

export function worldgenTopics() {
  return ENTRIES.map((entry) => entry.keys[0])
}
