function entryOf(row) {
  const [name, aliases, kind, where, tool, use] = row
  const toolText = tool === '—' ? '' : `需要：${TOOL_LEVEL[tool] || tool}。`
  return {
    name,
    aliases: String(aliases || '').split(/\s+/).filter(Boolean),
    kind,
    steps: [
      `在哪找：${where}。`,
      toolText ? `怎么拿：${toolText}` : '',
      `用来做什么：${use}。`,
    ].filter(Boolean),
  }
}

const ENTRIES = TABLE.map(entryOf)

/** 按名称/别名匹配材料；匹配不到返回 null。 */
export function lookupMaterial(topic) {
  const text = String(topic ?? '').toLowerCase()
  if (text.length === 0) return null
  let best = null
  let bestScore = 0
  for (const entry of ENTRIES) {
    let score = 0
    if (text.includes(entry.name.toLowerCase())) score += entry.name.length * 2
    for (const alias of entry.aliases) if (text.includes(alias.toLowerCase())) score += alias.length
    if (score > bestScore) { best = entry; bestScore = score }
  }
  if (best === null) return null
  return {
    method: `${best.name}（${KIND_ZH[best.kind] || best.kind}）：${best.steps[0].replace('在哪找：', '').replace(/。$/, '')}。`,
    steps: best.steps.slice(),
    caveat: '材料总表（按服务器版本 26.1 的生成数据）',
    source: 'worldgen',
    title: best.name,
  }
}

/** 总目录：按类别列出所有材料名，让她知道“都有什么”。 */
export function materialIndex(kind = null) {
  const kinds = kind === null ? Object.keys(KIND_ZH) : [kind]
  const lines = []
  for (const k of kinds) {
    const names = ENTRIES.filter((entry) => entry.kind === k).map((entry) => entry.name)
    if (names.length > 0) lines.push(`${KIND_ZH[k]}（${names.length}）：${names.join('、')}`)
  }
  return lines.join('\n')
}

export function materialCount() {
  return ENTRIES.length
}
